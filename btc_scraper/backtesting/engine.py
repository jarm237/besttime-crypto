def atr_percent_to_price_distance(price: float, atr_percent: float) -> float:
    """Convert percent units (0.84 == 0.84%) to an absolute price distance."""
    price_value = float(price)
    percent_value = float(atr_percent)
    if price_value <= 0 or percent_value < 0:
        raise ValueError("price must be > 0 and atr_percent must be >= 0")
    return price_value * percent_value / 100.0


class BacktestEngine:
    """
    Event-driven historical backtester modeling transaction costs, spread, slippage, and latency.
    """
    def __init__(self, config: BacktestConfig):
        self.config = config
        self.cost_model = CostModel(config.fee_model)
        self.slippage_model = SlippageModel(config.slippage_model)
        self.latency_model = LatencyModel(config.latency_model)

    def run(
        self,
        candles_dict: Dict[str, List[Dict[str, Any]]],
        signals: List[Dict[str, Any]]
    ) -> BacktestResult:
        """
        Runs the event-driven backtest simulation.
        
        Args:
            candles_dict: Map of coin name to list of candles (sorted by timestamp)
            signals: List of historical signal records generated by models
        """
        run_id = str(uuid.uuid4())[:8]
        
        # 1. Align timelines: get sorted union of all timestamps
        all_timestamps = set()
        for coin, candles in candles_dict.items():
            for c in candles:
                t = c["time"]
                if not isinstance(t, str):
                    t = pd.to_datetime(t).strftime("%Y-%m-%d %H:%M:%S")
                else:
                    try:
                        t = pd.to_datetime(t).strftime("%Y-%m-%d %H:%M:%S")
                    except Exception:
                        pass
                c["time"] = t
                all_timestamps.add(t)
        sorted_times = sorted(list(all_timestamps))
        
        # Create quick lookup: coin -> time -> (candle_index, candle_dict)
        candle_lookup = {}
        for coin, candles in candles_dict.items():
            candle_lookup[coin] = {
                c["time"]: (idx, c) for idx, c in enumerate(candles)
            }

        # Create quick lookup: time -> list of signals
        signal_lookup = {}
        for s in signals:
            t = s["entry_time"]
            if not isinstance(t, str):
                t = pd.to_datetime(t).strftime("%Y-%m-%d %H:%M:%S")
            else:
                try:
                    t = pd.to_datetime(t).strftime("%Y-%m-%d %H:%M:%S")
                except Exception:
                    pass
            signal_lookup.setdefault(t, []).append(s)

        # 2. Portfolio state
        initial_capital = self.config.initial_capital
        cash = initial_capital
        open_positions = {}  # coin -> position_dict
        trade_log = []
        equity_history = []
        
        max_positions = 3
        max_holding_bars = 48  # Default limit
        
        for current_time in sorted_times:
            # Format time string for signal lookup
            time_str = current_time
            if isinstance(current_time, datetime):
                time_str = current_time.strftime("%Y-%m-%d %H:%M:%S")
            elif isinstance(current_time, pd.Timestamp):
                time_str = current_time.strftime("%Y-%m-%d %H:%M:%S")

            # 2.1 Calculate current equity
            current_equity = cash
            for coin, pos in open_positions.items():
                if coin in candle_lookup and time_str in candle_lookup[coin]:
                    _, current_candle = candle_lookup[coin][time_str]
                    current_price = current_candle["close"]
                    
                    # Unfinished position valuation
                    if pos["type"] == "LONG":
                        current_equity += pos["units"] * current_price
                    else:  # SHORT
                        current_equity += pos["units"] * (2 * pos["entry_price"] - current_price)
            
            equity_history.append({
                "time": current_time,
                "equity": current_equity
            })

            # 2.2 Process exit triggers for active positions
            closed_coins = []
            for coin, pos in open_positions.items():
                if coin not in candle_lookup or time_str not in candle_lookup[coin]:
                    continue
                
                c_idx, candle = candle_lookup[coin][time_str]
                high = candle["high"]
                low = candle["low"]
                close = candle["close"]
                
                pos["hold_bars"] += 1

                long_position = pos["type"] == "LONG"
                sl_triggered = low <= pos["sl"] if long_position else high >= pos["sl"]
                tp_triggered = (
                    high >= min(pos["tp1"], pos["tp2"])
                    if long_position
                    else low <= max(pos["tp1"], pos["tp2"])
                )
                if sl_triggered and tp_triggered:
                    policy = str(self.config.same_candle_policy).upper()
                    if policy == "LOWER_TIMEFRAME_REPLAY":
                        raise ValueError("LOWER_TIMEFRAME_REPLAY requires lower-timeframe candle input")
                    if policy == "AMBIGUOUS_EXCLUDE":
                        pos.setdefault("ambiguous_bars_excluded", 0)
                        pos["ambiguous_bars_excluded"] += 1
                        continue
                    if policy == "OPTIMISTIC_TP_FIRST":
                        sl_triggered = False
                
                # Check Stop Loss (SL)
                sl_hit = False
                exit_price = 0.0
                exit_reason = ""
                
                if pos["type"] == "LONG":
                    if sl_triggered:
                        sl_hit = True
                        exit_price = pos["sl"]
                        exit_reason = "SL"
                else:  # SHORT
                    if sl_triggered:
                        sl_hit = True
                        exit_price = pos["sl"]
                        exit_reason = "SL"
                        
                if sl_hit:
                    # Liquidate position
                    self._close_position_event(
                        pos=pos,
                        exit_price=exit_price,
                        exit_reason=exit_reason,
                        current_idx=c_idx,
                        candles=candles_dict[coin],
                        cash_container=[cash],
                        trade_log=trade_log
                    )
                    cash = pos["exit_cash"]
                    closed_coins.append(coin)
                    continue

                # Check Take Profit 1 (TP1)
                if not pos["tp1_hit"]:
                    tp1_hit = False
                    if pos["type"] == "LONG" and high >= pos["tp1"]:
                        tp1_hit = True
                    elif pos["type"] == "SHORT" and low <= pos["tp1"]:
                        tp1_hit = True
                        
                    if tp1_hit:
                        # Close 50% partial exit
                        self._partial_close_event(
                            pos=pos,
                            exit_price=pos["tp1"],
                            exit_reason="TP1",
                            current_idx=c_idx,
                            candles=candles_dict[coin],
                            cash_container=[cash]
                        )
                        cash = pos["exit_cash"]

                # Check Take Profit 2 (TP2)
                tp2_hit = False
                if pos["type"] == "LONG" and high >= pos["tp2"]:
                    tp2_hit = True
                elif pos["type"] == "SHORT" and low <= pos["tp2"]:
                    tp2_hit = True
                    
                if tp2_hit:
                    self._close_position_event(
                        pos=pos,
                        exit_price=pos["tp2"],
                        exit_reason="TP2",
                        current_idx=c_idx,
                        candles=candles_dict[coin],
                        cash_container=[cash],
                        trade_log=trade_log
                    )
                    cash = pos["exit_cash"]
                    closed_coins.append(coin)
                    continue

                # Check Max Hold Timeout / Exit Signal
                has_exit_signal = False
                sig_list = signal_lookup.get(time_str, [])
                for s in sig_list:
                    if s["coin"] == coin:
                        sig_raw = str(s.get("signal_raw", "")).upper()
                        if pos["type"] == "LONG" and any(x in sig_raw for x in ["SELL", "BEAR"]):
                            has_exit_signal = True
                        elif pos["type"] == "SHORT" and any(x in sig_raw for x in ["BUY", "BULL"]):
                            has_exit_signal = True

                if pos["hold_bars"] >= max_holding_bars or has_exit_signal:
                    reason = "TIMEOUT" if pos["hold_bars"] >= max_holding_bars else "EXIT_SIGNAL"
                    self._close_position_event(
                        pos=pos,
                        exit_price=close,
                        exit_reason=reason,
                        current_idx=c_idx,
                        candles=candles_dict[coin],
                        cash_container=[cash],
                        trade_log=trade_log
                    )
                    cash = pos["exit_cash"]
                    closed_coins.append(coin)
                    continue

            for coin in closed_coins:
                del open_positions[coin]

            # 2.3 Process new entries from signals
            sig_list = signal_lookup.get(time_str, [])
            for sig in sig_list:
                coin = sig["coin"]
                if coin in open_positions:
                    continue
                if len(open_positions) >= max_positions:
                    break
                if coin not in candle_lookup or time_str not in candle_lookup[coin]:
                    continue

                # Determine direction
                sig_raw = str(sig.get("signal_raw", sig.get("signal", ""))).upper()
                is_buy = "BUY" in sig_raw or "STRONG BUY" in sig_raw
                is_sell = "SELL" in sig_raw or "STRONG SELL" in sig_raw
                
                # Exclude weak/neutral signals
                if "WEAK" in sig_raw or "NEUTRAL" in sig_raw or "HOLD" in sig_raw:
                    continue
                if not is_buy and not is_sell:
                    continue
                    
                direction = "LONG" if is_buy else "SHORT"
                c_idx, candle = candle_lookup[coin][time_str]
                
                # Check index range
                if c_idx >= len(candles_dict[coin]) - 1:
                    continue

                # Compute fill price with latency delay
                latency_res = self.latency_model.compute_delayed_execution(
                    candles=candles_dict[coin],
                    current_idx=c_idx,
                    is_buy=(direction == "LONG"),
                    timeframe_min=15
                )
                
                fill_idx = latency_res["fill_index"]
                base_price = latency_res["base_price"]
                latency_val = self.config.latency_model.get("latency_ms", 250)
                
                # Apply spread
                spread_bps = sig.get("spread_bps", 2.0)
                price_spread = self.cost_model.get_fill_price_with_spread(
                    base_price=base_price,
                    is_buy=(direction == "LONG"),
                    spread_bps=spread_bps
                )
                
                # Apply slippage
                atr_percent = float(sig.get("atr_percent", sig.get("atr_pct", 2.0)) or 0.0)
                atr_fraction = atr_percent / 100.0
                slippage_bps = self.slippage_model.calculate_slippage_bps(
                    atr_pct=atr_fraction,
                    order_size_pct_adv=0.001,  # Assume typical micro order size
                    spread_bps=spread_bps
                )
                execution_price = self.slippage_model.apply_slippage(
                    price=price_spread,
                    is_buy=(direction == "LONG"),
                    slippage_bps=slippage_bps
                )
                
                # Calculate SL & TP
                atr = atr_percent_to_price_distance(execution_price, atr_percent)
                support_distance = max(0.0, float(sig.get("distance_support_pct", 2.0) or 0.0)) / 100.0
                resistance_distance = max(0.0, float(sig.get("distance_resistance_pct", 2.0) or 0.0)) / 100.0
                support = execution_price * (1.0 - support_distance)
                resistance = execution_price * (1.0 + resistance_distance)
                bb_upper = execution_price * 1.05
                bb_middle = execution_price
                bb_lower = execution_price * 0.95
                
                tp_sl = calculate_tp_sl(
                    close=execution_price,
                    signal=sig_raw,
                    atr=atr,
                    support=support,
                    resistance=resistance,
                    bb_upper=bb_upper,
                    bb_middle=bb_middle,
                    bb_lower=bb_lower,
                    atr_sl_mult=1.2,
                    atr_tp_mult=2.0,
                    regime=sig.get("regime")
                )
                
                # Position Sizing: Allocate equal fraction of initial capital
                allocation = min(cash, initial_capital / max_positions)
                if allocation <= 0:
                    continue
                    
                units = allocation / execution_price
                
                # Calculate entry fees
                entry_fee = self.cost_model.calculate_fee(allocation, is_taker=True)
                
                # Costs bookkeeping
                spread_paid = abs(price_spread - base_price) * units
                slippage_paid = abs(execution_price - price_spread) * units
                
                cash -= (allocation + entry_fee)
                
                # Store position
                open_positions[coin] = {
                    "coin": coin,
                    "type": direction,
                    "units": units,
                    "entry_price": execution_price,
                    "entry_time": latency_res["fill_time"],
                    "entry_idx": fill_idx,
                    "sl": tp_sl["sl"],
                    "tp1": tp_sl["tp1"],
                    "tp2": tp_sl["tp2"],
                    "tp1_hit": False,
                    "hold_bars": 0,
                    "partial_pnl": 0.0,
                    "partial_exits": [],
                    "fee_paid": entry_fee,
                    "slippage_paid": slippage_paid,
                    "spread_paid": spread_paid,
                    "spread_bps": spread_bps,
                    "slippage_bps": slippage_bps,
                    "latency_ms": latency_val,
                    "regime": sig.get("regime", "Ranging"),
                    "regime_snapshot": sig.get("regime_snapshot"),
                    "atr_percent": atr_percent,
                    "atr_price_distance": atr,
                    "same_candle_policy": self.config.same_candle_policy,
                    "causal_risk_level": sig.get("causal_risk_level", "MEDIUM"),
                    "meta_confidence_bucket": "HIGH" if sig.get("signal_score", 50.0) >= 70 else "MEDIUM"
                }

        # 3. Compile report
        metrics = calculate_metrics(trade_log, equity_history, initial_capital, self.config.timeframe)
        
        # Sprints 9.5, 9.6, 9.7 integrations:
        regime_metrics = RegimeSplitAnalyzer.analyze(trade_log)
        stress_metrics = StressTestEngine.analyze(self, candles_dict, signals)
        mc_metrics = MonteCarloEngine.analyze(trade_log, initial_capital)
        attribution = AttributionAnalyzer.analyze(trade_log)
        
        # Strategy Approval Check
        approval_status = ReportBuilder.check_approval_gate(metrics, mc_metrics, regime_metrics)

        return BacktestResult(
            run_id=run_id,
            timestamp=datetime.now().isoformat(),
            config=self.config.to_dict(),
            metrics=metrics,
            trades=trade_log,
            regime_metrics=regime_metrics,
            stress_metrics=stress_metrics,
            monte_carlo_metrics=mc_metrics,
            attribution=attribution,
            approval_status=approval_status
        )

    def _partial_close_event(
        self,
        pos: Dict[str, Any],
        exit_price: float,
        exit_reason: str,
        current_idx: int,
        candles: List[Dict[str, Any]],
        cash_container: List[float]
    ) -> None:
        """Handles 50% partial exit on TP1."""
        pos["tp1_hit"] = True
        half_units = pos["units"] / 2
        
        # Apply exit models
        latency_res = self.latency_model.compute_delayed_execution(
            candles=candles,
            current_idx=current_idx,
            is_buy=(pos["type"] == "SHORT")
        )
        
        base_exit = latency_res["base_price"]
        # Apply exit spread & slippage
        is_buy_exit = (pos["type"] == "SHORT")
        price_spread = self.cost_model.get_fill_price_with_spread(base_exit, is_buy_exit, pos["spread_bps"])
        execution_exit = self.slippage_model.apply_slippage(price_spread, is_buy_exit, pos["slippage_bps"])
        
        # Calculate PnL
        notional_entry = half_units * pos["entry_price"]
        notional_exit = half_units * execution_exit
        
        if pos["type"] == "LONG":
            raw_pnl = notional_exit - notional_entry
            cash_back = notional_exit
        else:
            raw_pnl = notional_entry - notional_exit
            cash_back = notional_entry + (notional_entry - notional_exit)

        fee = self.cost_model.calculate_fee(notional_exit, is_taker=True)
        net_pnl = raw_pnl - fee
        
        pos["units"] -= half_units
        pos["partial_pnl"] += net_pnl
        pos["fee_paid"] += fee
        
        spread_cost = abs(price_spread - base_exit) * half_units
        slippage_cost = abs(execution_exit - price_spread) * half_units
        pos["spread_paid"] += spread_cost
        pos["slippage_paid"] += slippage_cost
        
        pos["partial_exits"].append({
            "reason": exit_reason,
            "exit_time": latency_res["fill_time"],
            "exit_price": execution_exit,
            "pnl": net_pnl
        })
        
        # Add back to cash
        cash_container[0] += (cash_back - fee)
        pos["exit_cash"] = cash_container[0]

    def _close_position_event(
        self,
        pos: Dict[str, Any],
        exit_price: float,
        exit_reason: str,
        current_idx: int,
        candles: List[Dict[str, Any]],
        cash_container: List[float],
        trade_log: List[Dict[str, Any]]
    ) -> None:
        """Handles full liquidation of the remaining position."""
        remaining_units = pos["units"]
        
        # Exit models
        latency_res = self.latency_model.compute_delayed_execution(
            candles=candles,
            current_idx=current_idx,
            is_buy=(pos["type"] == "SHORT")
        )
        
        base_exit = latency_res["base_price"]
        is_buy_exit = (pos["type"] == "SHORT")
        price_spread = self.cost_model.get_fill_price_with_spread(base_exit, is_buy_exit, pos["spread_bps"])
        execution_exit = self.slippage_model.apply_slippage(price_spread, is_buy_exit, pos["slippage_bps"])
        
        notional_entry = remaining_units * pos["entry_price"]
        notional_exit = remaining_units * execution_exit
        
        if pos["type"] == "LONG":
            raw_pnl = notional_exit - notional_entry
            cash_back = notional_exit
        else:
            raw_pnl = notional_entry - notional_exit
            cash_back = notional_entry + (notional_entry - notional_exit)

        fee = self.cost_model.calculate_fee(notional_exit, is_taker=True)
        net_pnl = raw_pnl - fee
        
        total_pnl = pos["partial_pnl"] + net_pnl
        pos["fee_paid"] += fee
        
        spread_cost = abs(price_spread - base_exit) * remaining_units
        slippage_cost = abs(execution_exit - price_spread) * remaining_units
        pos["spread_paid"] += spread_cost
        pos["slippage_paid"] += slippage_cost
        
        # Return cash
        cash_container[0] += (cash_back - fee)
        pos["exit_cash"] = cash_container[0]
        
        # Log final trade
        trade_log.append({
            "coin": pos["coin"],
            "type": pos["type"],
            "entry_time": pos["entry_time"],
            "exit_time": latency_res["fill_time"],
            "entry_price": pos["entry_price"],
            "exit_price": execution_exit,
            "pnl": total_pnl,
            "result": exit_reason,
            "hold_bars": pos["hold_bars"],
            "fee_paid": pos["fee_paid"],
            "slippage_paid": pos["slippage_paid"],
            "spread_paid": pos["spread_paid"],
            "fee_bps": pos["fee_paid"] / (pos["entry_price"] * (pos["units"] * 2)) * 10000.0 if pos["units"] > 0 else 0.0,
            "spread_bps": pos["spread_bps"],
            "slippage_bps": pos["slippage_bps"],
            "latency_ms": pos["latency_ms"],
            "regime": pos["regime"],
            "regime_snapshot": pos.get("regime_snapshot"),
            "same_candle_policy": pos.get("same_candle_policy"),
            "economic_win": total_pnl > 0,
            "target_hit_win": exit_reason in {"TP1", "TP2"},
            "timeout_profitable": exit_reason == "TIMEOUT" and total_pnl > 0,
            "causal_risk_level": pos["causal_risk_level"],
            "meta_confidence_bucket": pos["meta_confidence_bucket"]
        })
